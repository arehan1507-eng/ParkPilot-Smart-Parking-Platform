#  Heart Disease Prediction Using Machine Learning

A machine learning project that predicts the likelihood of heart disease based on clinical and demographic patient features.

The project explores data preprocessing, exploratory data analysis, feature selection, model training, and evaluation using machine learning classification algorithms.

## 🚀 Project Overview

Heart disease is one of the major health challenges worldwide. Machine learning can be used to analyze medical datasets and identify patterns associated with heart disease.

In this project, a heart disease dataset is processed and used to train classification models that predict whether a patient is likely to have heart disease.

> **Note:** This project is for educational and research purposes only and is not intended for medical diagnosis.

## 🎯 Objectives

* Analyze a heart disease dataset
* Perform data preprocessing
* Explore relationships between different features
* Train machine learning classification models
* Evaluate model performance
* Compare classification results
* Understand which features contribute to predictions

## 📊 Dataset

The project uses a heart disease dataset containing clinical and demographic attributes such as:

* Age
* Sex
* Chest pain type
* Resting blood pressure
* Cholesterol
* Fasting blood sugar
* Resting ECG results
* Maximum heart rate
* Exercise-induced angina
* ST depression
* Slope
* Number of major vessels
* Thalassemia
* Heart disease target

The dataset is used for educational machine learning experimentation.

